def skyline(s, base, color, seed, alpha=1.0, tall=1.0, lit=None):
    rng = random.Random(seed)
    x = -40
    while x < W + 40:
        w = rng.randint(50, 150)
        h = int(rng.uniform(60, 240) * tall)
        s.rect([x, base - h, x + w, base], color, alpha)
        if rng.random() < 0.28:                       # temple spire
            sh = int(h * 0.55)
            s.poly([(x + w * 0.5, base - h - sh), (x + w * 0.78, base - h),
                    (x + w * 0.22, base - h)], color, alpha)
        if lit and rng.random() < 0.55:               # windows
            cols = max(1, w // 34)
            rows = max(1, h // 40)
            for c in range(cols):
                for r in range(rows):
                    if rng.random() < lit:
                        wx = x + 10 + c * 34
                        wy = base - h + 12 + r * 40
                        s.rect([wx, wy, wx + 9, wy + 12], BRASS, 0.55)
        x += w + rng.randint(8, 40)


def window_wall(s, box, color, seed, lit=0.35, cols=6, rows=8):
    x0, y0, x1, y1 = box
    s.rect(box, color)
    rng = random.Random(seed)
    for c in range(cols):
        for r in range(rows):
            wx = x0 + 14 + c * (x1 - x0 - 28) / cols
            wy = y0 + 14 + r * (y1 - y0 - 28) / rows
            if rng.random() < lit:
                s.rect([wx, wy, wx + 12, wy + 14], BRASS, 0.5)


def crowd(s, cx, base, n, scale, color, spread=520, alpha=0.9, seed=3):
    rng = random.Random(seed)
    for i in range(n):
        x = cx + rng.uniform(-spread, spread)
        y = base + rng.uniform(-10, 18)
        h = scale * rng.uniform(0.85, 1.15)
        s.ellipse([x - 5, y - h, x + 5, y - h + 10], color, alpha)
        s.rect([x - 7, y - h + 9, x + 7, y], color, alpha)


def _poly(d, pts, mode, w):
    if mode == "fill":
        d.polygon(pts, fill=255)
    else:
        d.polygon(pts, fill=None, outline=255, width=max(1, int(w)))


def _ell(d, box, mode, w):
    if mode == "fill":
        d.ellipse(box, fill=255)
    else:
        d.ellipse(box, fill=None, outline=255, width=max(1, int(w)))


def _taper(d, p0, p1, w0, w1, mode, w):
    """Tapered limb segment from p0 (width w0) to p1 (width w1)."""
    x0, y0 = p0
    x1, y1 = p1
    dx, dy = x1 - x0, y1 - y0
    L = math.hypot(dx, dy) or 1.0
    nx, ny = -dy / L, dx / L
    a = (x0 + nx * w0 / 2, y0 + ny * w0 / 2)
    b = (x1 + nx * w1 / 2, y1 + ny * w1 / 2)
    c = (x1 - nx * w1 / 2, y1 - ny * w1 / 2)
    e = (x0 - nx * w0 / 2, y0 - ny * w0 / 2)
    _poly(d, [a, b, c, e], mode, w)
    if mode == "fill":                                  # rounded joint
        _ell(d, [x1 - w1 / 2, y1 - w1 / 2, x1 + w1 / 2, y1 + w1 / 2], mode, w)


def _skeleton(pose, cx, base, u, lean=0.0):
    """Joint positions for a 100-unit figure. Returns a dict in pixel coords."""
    dx = lean * u
    hip_y = base - 47 * u
    sh_y = base - 78 * u
    head = (cx + dx, base - 92 * u)
    neck = (cx + dx, head[1] + 8.4 * u)
    shl = (cx - 15 * u + dx, sh_y)
    shr = (cx + 15 * u + dx, sh_y)
    torso = [(cx - 15 * u + dx, sh_y - 1 * u), (cx + 15 * u + dx, sh_y - 1 * u),
             (cx + 16 * u + dx, base - 70 * u), (cx + 12 * u + dx * .6, hip_y),
             (cx + 12.5 * u, hip_y), (cx - 12.5 * u, hip_y),
             (cx - 12 * u + dx * .6, hip_y), (cx - 16 * u + dx, base - 70 * u)]
    P = {"head": head, "neck": neck, "torso": torso, "shoulders": (shl, shr)}
    if pose == "catch":
        P["arms"] = [((cx - 24 * u, base - 90 * u), (cx - 27 * u, base - 102 * u)),
                     ((cx + 24 * u, base - 90 * u), (cx + 27 * u, base - 102 * u))]
        P["legs"] = [((cx - 14 * u, base - 27 * u), (cx - 20 * u, base - 2 * u)),
                     ((cx + 14 * u, base - 27 * u), (cx + 20 * u, base - 2 * u))]
    elif pose == "kneel":
        P["torso"] = [(x, y + 10 * u) for (x, y) in P["torso"]]
        P["head"] = (head[0], head[1] + 10 * u)
        P["neck"] = (neck[0], neck[1] + 10 * u)
        P["shoulders"] = ((shl[0], shl[1] + 10 * u), (shr[0], shr[1] + 10 * u))
        P["arms"] = [((cx - 22 * u, base - 52 * u), (cx - 26 * u, base - 38 * u)),
                     ((cx + 20 * u, base - 60 * u), (cx + 30 * u, base - 70 * u))]
        P["legs"] = [((cx - 17 * u, base - 16 * u), (cx - 27 * u, base - 2 * u)),
                     ((cx + 14 * u, base - 27 * u), (cx + 15 * u, base - 2 * u))]
    elif pose == "brace":
        P["arms"] = [((cx - 26 * u, base - 92 * u), (cx - 30 * u, base - 104 * u)),
                     ((cx + 25 * u, base - 62 * u), (cx + 30 * u, base - 48 * u))]
        P["legs"] = [((cx - 17 * u, base - 26 * u), (cx - 25 * u, base - 2 * u)),
                     ((cx + 17 * u, base - 26 * u), (cx + 25 * u, base - 2 * u))]
    elif pose == "run":
        P["arms"] = [((cx - 24 * u + dx, base - 66 * u), (cx - 30 * u + dx, base - 82 * u)),
                     ((cx + 24 * u + dx, base - 62 * u), (cx + 32 * u + dx, base - 50 * u))]
        P["legs"] = [((cx - 24 * u, base - 26 * u), (cx - 34 * u, base - 4 * u)),
                     ((cx + 12 * u, base - 30 * u), (cx + 30 * u, base - 40 * u))]
    elif pose == "sit":
        P["torso"] = [(x, y + 2 * u) for (x, y) in P["torso"]]
        P["head"] = (head[0], head[1] + 2 * u)
        P["neck"] = (neck[0], neck[1] + 2 * u)
        P["shoulders"] = ((shl[0], shl[1] + 2 * u), (shr[0], shr[1] + 2 * u))
        P["arms"] = [((cx - 24 * u, base - 50 * u), (cx - 24 * u, base - 36 * u)),
                     ((cx + 24 * u, base - 50 * u), (cx + 24 * u, base - 36 * u))]
        P["legs"] = [((cx - 26 * u, base - 24 * u), (cx - 26 * u, base - 2 * u)),
                     ((cx + 26 * u, base - 24 * u), (cx + 26 * u, base - 2 * u))]
    elif pose == "lie":
        P["head"] = (cx - 44 * u, base - 12 * u)
        P["neck"] = (cx - 36 * u, base - 12 * u)
        P["torso"] = [(cx - 36 * u, base - 20 * u), (cx - 36 * u, base - 4 * u),
                      (cx + 10 * u, base - 3 * u), (cx + 10 * u, base - 20 * u)]
        P["shoulders"] = ((cx - 34 * u, base - 19 * u), (cx - 34 * u, base - 5 * u))
        P["arms"] = [((cx - 52 * u, base - 22 * u), (cx - 62 * u, base - 26 * u)),
                     ((cx - 30 * u, base - 26 * u), (cx - 22 * u, base - 34 * u))]
        P["legs"] = [((cx + 28 * u, base - 14 * u), (cx + 44 * u, base - 10 * u)),
                     ((cx + 28 * u, base - 6 * u), (cx + 42 * u, base - 2 * u))]
    else:  # stand
        P["arms"] = [((cx - 21 * u + dx, base - 63 * u), (cx - 22 * u + dx, base - 47 * u)),
                     ((cx + 21 * u + dx, base - 63 * u), (cx + 22 * u + dx, base - 47 * u))]
        P["legs"] = [((cx - 9 * u, base - 25 * u), (cx - 10 * u, base - 2 * u)),
                     ((cx + 9 * u, base - 25 * u), (cx + 10 * u, base - 2 * u))]
    return P


def person(s, cx, base, h, color, pose="stand", alpha=1.0, lean=0.0,
           style="fill", lw=1.0, rim=None):
    u = h / 100.0
    if rim:
        person(s, cx - 1.4 * u, base - 1.4 * u, h, rim, pose, alpha * 0.85, lean,
               style, lw, None)
    P = _skeleton(pose, cx, base, u, lean)
    im = s._new()
    d = ImageDraw.Draw(im)
    _poly(d, P["torso"], style, 3.4 * u * lw)
    _taper(d, P["neck"], (P["neck"][0], P["neck"][1] + 1.2 * u),
           19 * u, 30 * u, style, 3.4 * u * lw)
    _ell(d, [P["head"][0] - 8.2 * u, P["head"][1] - 8.6 * u,
             P["head"][0] + 8.2 * u, P["head"][1] + 8.6 * u], style, 3.4 * u * lw)
    for sh, (el, wr) in zip(P["shoulders"], P["arms"]):
        _taper(d, sh, el, 10.5 * u, 8.5 * u, style, 3.4 * u * lw)
        _taper(d, el, wr, 8.5 * u, 6.5 * u, style, 3.4 * u * lw)
    hip_y = base - 46 * u
    for sgn, (kn, an) in zip((-1, 1), P["legs"]):
        _taper(d, (cx + sgn * 7.5 * u, hip_y), kn, 14 * u, 10 * u, style, 3.4 * u * lw)
        _taper(d, kn, an, 10 * u, 7.5 * u, style, 3.4 * u * lw)
        if style == "fill":                              # foot
            fx0, fx1 = sorted((an[0] - 3 * u, an[0] + sgn * 7 * u))
            d.rectangle([fx0, an[1] - 2 * u, fx1, base], fill=255)
    s._blend(im, color, alpha)
    return P


def hero(s, cx, base, h, panels=5, alpha=1.0, pose="stand", style="fill",
         color="#12172C", rim=None):
    """Arin in the Palm-Leaf mantle: hood, visor, five chest panels, shield, no cape."""
    u = h / 100.0
    if rim:                                    # thin warm rim from the sun behind
        hero(s, cx - 1.15 * u, base - 1.15 * u, h, panels, alpha * 0.85, pose, style,
             color=rim, rim=None)
    if pose != "lie":
        # leaf mantle hanging behind the right shoulder
        s.poly([(cx + 7 * u, base - 80 * u), (cx + 26 * u, base - 68 * u),
                (cx + 24 * u, base - 30 * u), (cx + 13 * u, base - 38 * u),
                (cx + 6 * u, base - 58 * u)], "#0B0F1C", alpha)
        s.line([(cx + 7 * u, base - 80 * u), (cx + 26 * u, base - 68 * u),
                (cx + 24 * u, base - 30 * u)], BRASS, max(2, 1.9 * u), alpha * 0.7)
        # shield on the left forearm, behind the body
        sx, sy = cx - 28 * u, base - 55 * u
        s.poly([(sx, sy - 15 * u), (sx + 11 * u, sy - 9 * u), (sx + 11 * u, sy + 11 * u),
                (sx, sy + 16 * u), (sx - 8 * u, sy + 5 * u)], "#0A0E1E", alpha)
        s.line([(sx, sy - 15 * u), (sx + 11 * u, sy - 9 * u), (sx + 11 * u, sy + 11 * u),
                (sx, sy + 16 * u), (sx - 8 * u, sy + 5 * u), (sx, sy - 15 * u)],
               BRASS, max(2, 2 * u), alpha * 0.85)
        s.ellipse([sx - 1 * u, sy - 3 * u, sx + 4 * u, sy + 2 * u], BRASS, alpha * 0.7)
    person(s, cx, base, h, color, pose=pose, alpha=alpha, style=style)
    if pose != "lie":
        # hip guard keeps the waist reading as one mass
        s.poly([(cx - 14 * u, base - 51 * u), (cx + 14 * u, base - 51 * u),
                (cx + 12 * u, base - 41 * u), (cx - 12 * u, base - 41 * u)],
               color, alpha)
    # hood: crown + jaw
    s.poly([(cx - 9 * u, base - 96 * u), (cx, base - 104 * u),
            (cx + 9 * u, base - 96 * u)], color, alpha)
    s.poly([(cx - 8.2 * u, base - 86 * u), (cx - 5 * u, base - 82.5 * u),
            (cx + 5 * u, base - 82.5 * u), (cx + 8.2 * u, base - 86 * u)],
           color, alpha)
    # visor
    s.rect([cx - 7.4 * u, base - 93.5 * u, cx + 7.4 * u, base - 89.2 * u],
           BRASS, alpha * 0.95)
    s.rect([cx - 7.4 * u, base - 92.3 * u, cx + 7.4 * u, base - 90.8 * u],
           "#FFE9B0", alpha * 0.85)
    # collar, belt, boot cuffs
    s.line([(cx - 12 * u, base - 77.5 * u), (cx + 12 * u, base - 77.5 * u)],
           BRASS, max(2, 1.9 * u), alpha * 0.8)
    s.line([(cx - 12 * u, base - 49 * u), (cx + 12 * u, base - 49 * u)],
           BRASS, max(2, 1.9 * u), alpha * 0.6)
    for sgn in (-1, 1):
        bx = cx + sgn * 9.5 * u
        s.rect([bx - 5 * u, base - 13 * u, bx + 5 * u, base - 9 * u], BRASS,
               alpha * 0.55)
    # five chest panels, left to right
    for i in range(5):
        px = cx - 8.4 * u + i * 4.2 * u
        py = base - 66.5 * u
        on = i < panels
        s.ellipse([px - 2.6 * u, py - 2.6 * u, px + 2.6 * u, py + 2.6 * u],
                  ELEMENTS[i] if on else "#232941", alpha)
        if on:
            s.glow(px, py, 30 * u, ELEMENTS[i], 0.5 * alpha)


