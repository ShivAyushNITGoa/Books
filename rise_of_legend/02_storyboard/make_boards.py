def hx(s):
    return np.array([int(s[1:3], 16), int(s[3:5], 16), int(s[5:7], 16)], float)


def mix(a, b, t):
    return tuple((hx(a) * (1 - t) + hx(b) * t).astype(int))


class Scene:
    """RGB float canvas with flat-shape drawing, glows, halftone and grain."""

    def __init__(self, top=INK, bottom=INDIGO):
        t = np.linspace(0, 1, H)[:, None, None]
        self.a = (hx(top)[None, None, :] * (1 - t) + hx(bottom)[None, None, :] * t)
        self.a = np.repeat(self.a, W, axis=1)

    # -- primitives -----------------------------------------------------
    def _blend(self, mask, color, alpha=1.0):
        m = np.asarray(mask, dtype=np.float32) / 255.0
        m = (m * alpha)[:, :, None]
        c = np.array(hx(color) if isinstance(color, str) else color,
                     dtype=np.float32)[None, None, :]
        self.a = self.a * (1 - m) + c * m

    def _new(self):
        return Image.new("L", (W, H), 0)

    def poly(self, pts, color, alpha=1.0, outline=None, width=0):
        im = self._new()
        d = ImageDraw.Draw(im)
        if outline is None:
            d.polygon(pts, fill=255)
        else:
            d.polygon(pts, fill=None, outline=255, width=width)
        self._blend(im, color, alpha)

    def rect(self, box, color, alpha=1.0, radius=0):
        im = self._new()
        d = ImageDraw.Draw(im)
        if radius:
            d.rounded_rectangle(box, radius=radius, fill=255)
        else:
            d.rectangle(box, fill=255)
        self._blend(im, color, alpha)

    def ellipse(self, box, color, alpha=1.0):
        im = self._new()
        ImageDraw.Draw(im).ellipse(box, fill=255)
        self._blend(im, color, alpha)

    def line(self, pts, color, width, alpha=1.0):
        im = self._new()
        ImageDraw.Draw(im).line(pts, fill=255, width=int(width), joint="curve")
        self._blend(im, color, alpha)

    def glow(self, cx, cy, r, color, strength=1.0):
        y, x = np.ogrid[:H, :W]
        d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2) / r
        m = np.clip(1 - d, 0, 1) ** 2 * strength
        b = (hx(color) if isinstance(color, str) else np.array(color))[None, None, :] \
            * m[:, :, None]
        self.a = 255 - (255 - self.a) * (255 - b) / 255

    def shadow(self, cx, cy, r, strength=0.6):
        y, x = np.ogrid[:H, :W]
        d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2) / r
        m = np.clip(1 - d, 0, 1) ** 1.5 * strength
        self.a *= (1 - m[:, :, None])

    # -- texture --------------------------------------------------------
    def halftone(self, strength=0.16, period=6):
        y, x = np.mgrid[0:H, 0:W]
        dx = (x % period) - period / 2
        dy = (y % period) - period / 2
        m = ((dx * dx + dy * dy) < (period * 0.30) ** 2).astype(np.float32)
        self.a *= (1 - (m * strength)[:, :, None])

    def grain(self, amount=5.0, seed=0):
        rng = np.random.default_rng(seed)
        self.a = np.clip(self.a + rng.normal(0, amount, (H, W, 1)), 0, 255)

    def vignette(self, strength=0.5):
        y, x = np.mgrid[0:H, 0:W]
        d = np.sqrt(((x - W / 2) / (W / 2)) ** 2 + ((y - H / 2) / (H / 2)) ** 2) / 1.414
        m = np.clip((d - 0.50) / 0.50, 0, 1) ** 1.5 * strength
        self.a *= (1 - m[:, :, None])

    def save(self, path, quality=88):
        path.parent.mkdir(parents=True, exist_ok=True)
        Image.fromarray(np.clip(self.a, 0, 255).astype(np.uint8)).save(
            path, quality=quality, optimize=True, progressive=True)
        return path


